import { useCallback, useEffect, useRef, useState } from 'react'
import { streamResearch } from '../api/research'
import { STEPS } from '../constants/steps'

const initialStepStatus = () =>
  Object.fromEntries(STEPS.map((step) => [step.id, 'waiting']))

/**
 * Runs the research pipeline and exposes live state.
 *
 * status:     'idle' | 'running' | 'done' | 'error':                                           overall pipeline status
 * stepStatus: { search | reader | writer | critic: 'waiting' | 'running' | 'done' | 'error' }: individual step status
 * outputs:    { search | reader | writer | critic: string } (filled as each step finishes):    results generated by agents
 * 
 * AbortController is used to cancel the research run if needed: useRef is used
 * to store the AbortController instance across renders, updating it without causing re-renders.
 */
export function useResearch() {
  const [status, setStatus] = useState('idle')
  const [stepStatus, setStepStatus] = useState(initialStepStatus)
  const [outputs, setOutputs] = useState({})
  const [error, setError] = useState(null)
  const controllerRef = useRef(null)

  const reset = () => {
    setStepStatus(initialStepStatus())
    setOutputs({})
    setError(null)
  }

  const start = useCallback(async (topic) => {
    controllerRef.current?.abort()
    const controller = new AbortController()
    controllerRef.current = controller

    reset()
    setStatus('running')

    let finished = false

    try {
      for await (const { event, data } of streamResearch(topic, controller.signal)) {
        if (event === 'step') {
          setStepStatus((prev) => ({ ...prev, [data.step]: data.status }))
          if (data.status === 'done') {
            setOutputs((prev) => ({ ...prev, [data.step]: data.output }))
          }
        } else if (event === 'complete') {
          finished = true
          setStatus('done')
        } else if (event === 'error') {
          finished = true
          if (data.step) setStepStatus((prev) => ({ ...prev, [data.step]: 'error' }))
          setError(data.message)
          setStatus('error')
        }
      }

      if (!finished && !controller.signal.aborted) {
        setError('The connection closed before the pipeline finished.')
        setStatus('error')
      }
    } catch (err) {
      if (err.name === 'AbortError') return
      setError(err.message || 'Something went wrong.')
      setStatus('error')
    }
  }, [])

  const cancel = useCallback(() => {
    controllerRef.current?.abort()
    reset()
    setStatus('idle')
  }, [])

  // stop any in-flight request when the component unmounts
  useEffect(() => () => controllerRef.current?.abort(), [])

  return { status, stepStatus, outputs, error, start, cancel }
}